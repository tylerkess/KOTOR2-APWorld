"""Generate worlds/kotor2/tables.py from research/{vanilla,tslrcm,tslrcm_m478}/ (run tools/extract_research.py first).

usage: .venv/bin/python tools/gen_tables.py

tables.py is an ID ledger: existing quest and module IDs are kept, new ones are appended after the highest ID, and an
entry that disappears from the research is kept (marked missing) so its ID is never reused.
"""
from __future__ import annotations

import ast
import csv
import pprint
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESEARCH = ROOT / "research"
OUT = ROOT / "worlds" / "kotor2" / "tables.py"
PROFILES = ("vanilla", "tslrcm", "tslrcm_m478")

HEADER = '''"""Generated by tools/gen_tables.py from the game's global.jrl and module list. Do not edit by hand.

QUESTS: tag -> (id, journal name, planet row in planetary.2da (-1 = none), end entry ids, profiles)
MODULES: resref -> (id, area name, profiles)
IDs are an append-only ledger: never renumber or reuse one.
"""
'''


def read(profile: str, name: str) -> list[dict[str, str]]:
    path = RESEARCH / profile / name
    return list(csv.DictReader(path.open(encoding="utf-8"), delimiter="\t")) if path.exists() else []


def existing() -> tuple[dict, dict]:
    if not OUT.exists():
        return {}, {}
    tree = ast.parse(OUT.read_text(encoding="utf-8"))
    values = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            values[node.targets[0].id] = ast.literal_eval(node.value)
    return values.get("QUESTS", {}), values.get("MODULES", {})


def clean(text: str) -> str:
    return text.replace("<FullName>", "the Exile").replace("<PlayerName>", "the Exile").strip()


def main() -> None:
    old_quests, old_modules = existing()
    quests: dict[str, dict] = {}
    for profile in PROFILES:
        for row in read(profile, "journal.tsv"):
            q = quests.setdefault(row["tag"], {"name": clean(row["quest"]), "planet": int(row["planet_id"]),
                                               "ends": set(), "profiles": set()})
            q["profiles"].add(profile)
            if row["end"] == "1":
                q["ends"].add(int(row["entry_id"]))
    modules: dict[str, dict] = {}
    for profile in PROFILES:
        for row in read(profile, "modules.tsv"):
            m = modules.setdefault(row["module"], {"name": row["area_name"], "profiles": set()})
            m["profiles"].add(profile)

    next_q = max([v[0] for v in old_quests.values()], default=-1) + 1
    out_q = {}
    for tag in list(old_quests) + [t for t in quests if t not in old_quests]:
        if tag in quests:
            q = quests[tag]
            qid = old_quests[tag][0] if tag in old_quests else next_q
            if tag not in old_quests:
                next_q += 1
            out_q[tag] = (qid, q["name"], q["planet"], tuple(sorted(q["ends"])), tuple(sorted(q["profiles"])))
        else:
            out_q[tag] = (*old_quests[tag][:4], ())  # gone from the game data: keep the ID, no profile has it
    next_m = max([v[0] for v in old_modules.values()], default=-1) + 1
    out_m = {}
    for mod in list(old_modules) + [m for m in sorted(modules) if m not in old_modules]:
        if mod in modules:
            mid = old_modules[mod][0] if mod in old_modules else next_m
            if mod not in old_modules:
                next_m += 1
            out_m[mod] = (mid, modules[mod]["name"], tuple(sorted(modules[mod]["profiles"])))
        else:
            out_m[mod] = (*old_modules[mod][:2], ())

    body = HEADER + "\nQUESTS = " + pprint.pformat(out_q, width=120, sort_dicts=False) + "\n\nMODULES = " + \
        pprint.pformat(out_m, width=120, sort_dicts=False) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(out_q)} quests, {len(out_m)} modules")


if __name__ == "__main__":
    main()
