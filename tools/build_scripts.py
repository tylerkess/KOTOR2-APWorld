"""Build the game-side files into build/override/ from nss/ and the player's own game files.

usage: .venv/bin/python tools/build_scripts.py "<KOTOR 2 folder>" [--profile vanilla|tslrcm|tslrcm_m478] [--out DIR]

The profile is detected from what the game will load (Workshop items Steam lists as installed, plus the game folder,
so manual installs count): M4-78's modules mean tslrcm_m478, TSLRCM's restored HK factory means tslrcm.

1. Generates nss/ap_generated.nss from worlds/kotor2/protocol.py (visit/quest tables, planet locks).
2. Compiles ap_tick.nss and ap_gm_lock.nss with PyKotor's compiler and nwscript.nss plus the bridge routines 877-879.
3. Patches the game's own a_galaxymap.ncs (module 003EBO, as the profile sees it): one ExecuteScript("ap_gm_lock")
   right before its ShowGalaxyMap call. Everything else in it is the original bytecode.
4. Writes globalcat.2da: the profile's effective table plus our rows (docs/DESIGN.md, State in the save).
Nothing of the game's is redistributed by this repository: steps 3 and 4 run on the player's machine.
"""
