def _fix_engine_call_order() -> None:
    """PyKotor (2.3.x) pushes an engine call's arguments first to last, to suit its own interpreter. The game pops them
    the other way: its compiler pushes the last argument first, so the first is on top (see SetPlanetAvailable in the
    game's a_galaxymap.ncs). With PyKotor's order every call with two or more arguments aborts the script in game
    (SetGlobalBoolean pops an int where it wants the name). Reverse that one loop; fail loudly if PyKotor changes it."""
    import inspect
    import textwrap
    from pykotor.resource.formats.ncs.compiler import classes

    source = textwrap.dedent(inspect.getsource(classes.EngineCallExpression.compile))
    forward = "for i in range(len(self._args)):"
    if source.count(forward) != 1:
        raise SystemExit("build_scripts: PyKotor's EngineCallExpression.compile changed; recheck the argument order")
    namespace: dict = {}
    exec(compile(source.replace(forward, "for i in reversed(range(len(self._args))):"), classes.__file__, "exec"),
         vars(classes), namespace)
    classes.EngineCallExpression.compile = namespace["compile"]


_fix_engine_call_order()

NSS = ROOT / "nss"


def load_protocol():
    """worlds/kotor2/protocol.py without importing the world package (it needs Archipelago)."""
    pkg = ROOT / "worlds" / "kotor2"
    for name in ("tables", "protocol"):
        spec = importlib.util.spec_from_file_location(f"kotor2_build.{name}", pkg / f"{name}.py",
                                                      submodule_search_locations=None)
        module = importlib.util.module_from_spec(spec)
        sys.modules[f"kotor2_build.{name}"] = module
        if name == "protocol":
            module.__package__ = "kotor2_build"
        spec.loader.exec_module(module)
    return sys.modules["kotor2_build.protocol"]


# PyKotor's TSL table stops at 875; the game has one more (876 RebuildPartyTable). It is added so the bridge routines
# get the IDs the bridge serves.
VANILLA_876 = ScriptFunction(DataType.VOID, "RebuildPartyTable", [], "876", "")
BRIDGE_ROUTINES = [  # IDs 877, 878, 879: appended after the vanilla table, in this order
    ScriptFunction(DataType.INT, "APB_Version", [], "877: bridge protocol version, 0 without the bridge", ""),
    ScriptFunction(DataType.STRING, "APB_Recv", [], "878: next command from the client", ""),
    ScriptFunction(DataType.VOID, "APB_Send", [ScriptParam(DataType.STRING, "sEvent", None)],
                   "879: event to the client", ""),
]
FUNCTIONS = [*TSL_FUNCTIONS, VANILLA_876] if len(TSL_FUNCTIONS) == 876 else list(TSL_FUNCTIONS)
assert len(FUNCTIONS) == 877 and FUNCTIONS[876].name == "RebuildPartyTable", len(FUNCTIONS)
FUNCTIONS += BRIDGE_ROUTINES


def generate(protocol, profile: str) -> str:
    out = ["// Generated by tools/build_scripts.py from worlds/kotor2/protocol.py. Do not edit.",
           f'const string AP_TABLE_HASH = "{protocol.table_hash()}";',
           f'const string AP_CONTENT = "{profile}";',
           f"const int AP_COMMANDS_PER_TICK = {protocol.COMMANDS_PER_TICK};", ""]
    out.append("void AP_MarkVisit(string sModule) {")
    for i, module in enumerate(protocol.VISIT_ORDER):
        keyword = "if" if i == 0 else "else if"
        out.append(f'    {keyword} (sModule == "{module.upper()}") SetGlobalBoolean("{protocol.visit_global(module)}", TRUE);')
    out += ["}", "", "string AP_VisitBits() {", '    string s = "";']
    for module in protocol.VISIT_ORDER:
        out.append(f'    s = s + (GetGlobalBoolean("{protocol.visit_global(module)}") ? "1" : "0");')
    out += ["    return s;", "}", "", "string AP_QuestStates() {", '    string s = "";']
    for i, tag in enumerate(protocol.QUEST_ORDER):
        sep = "" if i == 0 else '"," + '
        out.append(f'    s = s + {sep}IntToString(GetJournalEntry("{tag}"));')
    out += ["    return s;", "}", "", "string AP_WatchedGlobals() {", '    string s = "";']
    for i, name in enumerate(protocol.WATCHED_GLOBALS):
        sep = "" if i == 0 else '"," + '
        out.append(f'    s = s + {sep}IntToString(GetGlobalNumber("{name}"));')
    m478_bit = protocol.PLANET_BITS["M4-78 Coordinates"][0]
    out += ["    return s;", "}", "",
            f"const int AP_OPT_M478 = {protocol.OPT_M478_BY_COORDINATES};",
            f"const int AP_M478_BIT = {m478_bit};",
            f"const int AP_M478_ROW = {protocol.M478_ROW};",
            f"const int AP_OPT_MASTERS = {protocol.OPT_MASTERS_SHUFFLED};",
            f"const int AP_OPT_ABSENT = {protocol.OPT_UNMET_MASTERS_ABSENT};",
            f"const int AP_OPT_REQUIRED_SHIFT = {protocol.OPT_MASTERS_REQUIRED_SHIFT};", ""]
    out += ["void AP_LatchMasters() {", '    int j = GetJournalEntry("LostJedi");']
    for m in protocol.MASTERS:
        cond = " || ".join([f"j == {e}" for e in m.journal] + [f'GetGlobalNumber("{m.dead}") == 1'] +
                           [f'GetGlobalNumber("{g}") == 1' for g in m.extra_met])
        out.append(f'    if (GetGlobalNumber("{m.met}") == 0 && ({cond})) SetGlobalNumber("{m.met}", 1);')
    out += ["}", "", "int AP_MasterItems() {", '    int b = GetGlobalNumber("AP_MITEMS");', "    int n = 0;"]
    for m in protocol.MASTERS:
        out.append(f"    if ((b & {1 << m.bit}) != 0) n = n + 1;")
    out += ["    return n;", "}", "", "void AP_MarkUnmetMasters() {"]
    for m in protocol.MASTERS:
        out.append(f'    if (GetGlobalNumber("{m.met}") == 0) SetGlobalNumber("{m.dead}", 1);')
    out += ["}", "", "void AP_LockPlanets() {"]
    for bit, rows in protocol.PLANET_BITS.values():
        for row in rows:
            out.append(f"    if (!AP_HasPlanetBit({bit})) SetPlanetSelectable({row}, FALSE);")
    out += ["}", ""]
    return "\n".join(out)


def compile_script(name: str) -> bytes:
    NssLexer()
    parser = NssParser(functions=FUNCTIONS, constants=TSL_CONSTANTS, library=TSL_LIBRARY,
                       library_lookup=[str(NSS)])
    ncs = NCS()
    parser.parser.parse((NSS / f"{name}.nss").read_text(encoding="utf-8"), tracking=True).compile(ncs)
    RemoveNopOptimizer().optimize(ncs)
    return bytes(bytes_ncs(ncs))


def check_xp_table(layers: Layers) -> None:
    """ap_tick's XS op assumes the d20 curve: level L to L+1 takes 1000 x L XP (exptable.2da)."""
    table = twoda.read(layers.resource("exptable", ResourceType.TwoDA))
    xp = table.column("xp")
    for level in range(1, 50):
        if int(xp[level]) - int(xp[level - 1]) != 1000 * level:
            raise SystemExit(f"exptable.2da: level {level} needs {int(xp[level]) - int(xp[level - 1])} XP, not "
                             f"{1000 * level}: ap_tick's XS delivery would be off (nss/ap_tick.nss)")


def check_argument_order() -> None:
    """SetGlobalNumber("X", 7) must push 7 before "X", like the game's own scripts (_fix_engine_call_order)."""
    NssLexer()
    parser = NssParser(functions=FUNCTIONS, constants=TSL_CONSTANTS, library=TSL_LIBRARY, library_lookup=[str(NSS)])
    ncs = NCS()
    parser.parser.parse('void main() { SetGlobalNumber("X", 7); }', tracking=True).compile(ncs)
    pushes = [ins.ins_type.name for ins in ncs.instructions if ins.ins_type.name in ("CONSTI", "CONSTS")]
    if pushes != ["CONSTI", "CONSTS"]:
        raise SystemExit(f"build_scripts: engine call arguments compile in the wrong order ({pushes})")


SHOW_GALAXY_MAP = 739
EXECUTE_SCRIPT = 8


def patch_galaxymap(original: bytes) -> bytes:
    """Insert ExecuteScript("ap_gm_lock", OBJECT_SELF, -1) right before every ShowGalaxyMap. Arguments are pushed
    last-first; ShowGalaxyMap's own argument is already on the stack and ExecuteScript leaves the stack as it was."""
    ncs = read_ncs(original)
    sites = [i for i, ins in enumerate(ncs.instructions)
             if ins.ins_type == NCSInstructionType.ACTION and ins.args[0] == SHOW_GALAXY_MAP]
    if not sites:
        raise SystemExit("a_galaxymap: no ShowGalaxyMap call found (unexpected script)")
    for site in reversed(sites):
        target = ncs.instructions[site]
        call = execute_script_call("ap_gm_lock")
        ncs.instructions[site:site] = call
        # Jumps that landed on ShowGalaxyMap must now land on the inserted call.
        for ins in ncs.instructions:
            if ins.jump is target:
                ins.jump = call[0]
    return bytes(bytes_ncs(ncs))


def execute_script_call(script: str) -> list[NCSInstruction]:
    """ExecuteScript(script, OBJECT_SELF, -1): arguments pushed last-first; leaves the stack as it found it."""
    return [
        NCSInstruction(NCSInstructionType.CONSTI, [-1]),
        NCSInstruction(NCSInstructionType.CONSTO, [0]),  # OBJECT_SELF
        NCSInstruction(NCSInstructionType.CONSTS, [script]),
        NCSInstruction(NCSInstructionType.ACTION, [EXECUTE_SCRIPT, 3]),
    ]


def prepend_execute(original: bytes, script: str) -> bytes:
    """Run `script` first, before anything else in the original."""
    ncs = read_ncs(original)
    first = ncs.instructions[0]
    call = execute_script_call(script)
    ncs.instructions[0:0] = call
    for ins in ncs.instructions:
        if ins.jump is first:
            ins.jump = call[0]
    return bytes(bytes_ncs(ncs))


def merged_globalcat(layers: Layers, protocol) -> bytes:
    """The profile's effective globalcat.2da plus our rows. Read with tools/twoda.py: PyKotor's reader returns blank
    cells for TSLRCM's copy (its data-size field is 0)."""
    table = twoda.read(layers.resource("globalcat", ResourceType.TwoDA))
    names = table.column("name")
    if len(names) < 500 or sum(1 for n in names if n) < len(names) * 0.9:
        raise SystemExit(f"globalcat.2da read back with {sum(1 for n in names if n)}/{len(names)} names: refusing")
    have = {n.lower() for n in names}
    rows = [(n, "Number") for n in protocol.NUMBER_GLOBALS] + \
           [(protocol.visit_global(m), "Boolean") for m in protocol.VISIT_ORDER]
    for name, kind in rows:
        if name.lower() not in have:
            table.add({"name": name, "type": kind})
    out = twoda.write(table)
    check = twoda.read(out)
    if check.rows[:len(names)] != [[n, t] for n, t in zip(names, table.column("type"))][:len(names)]:
        raise SystemExit("globalcat.2da did not survive a write/read round trip: refusing")
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("game")
    ap.add_argument("--profile", choices=PROFILES, default=None,
                    help="build for this profile's Workshop item instead of what is installed (default)")
    ap.add_argument("--out", default=str(ROOT / "build" / "override"))
    args = ap.parse_args()
    game = Path(args.game)
    layers = Layers(game, WORKSHOP_PROFILES[args.profile]) if args.profile else Layers.installed(game)
    profile = layers.profile
    if args.profile and profile != args.profile:
        raise SystemExit(f"--profile {args.profile}: those files look like {profile}")
    protocol = load_protocol()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    check_argument_order()
    check_xp_table(layers)
    (NSS / "ap_generated.nss").write_text(generate(protocol, profile), encoding="utf-8")
    for name in ("ap_tick", "ap_gm_lock", "ap_masters"):
        (out / f"{name}.ncs").write_bytes(compile_script(name))
    galaxymap = layers.module_resources("003ebo")[("a_galaxymap", ResourceType.NCS)]
    (out / "a_galaxymap.ncs").write_bytes(patch_galaxymap(galaxymap))
    # The masters' meeting (650DAN) spawns each master unless their dead flag is set: TSLRCM in the area's OnEnter
    # (k_650enter), vanilla in each master's OnSpawn (k_def_650*). ap_masters runs first in all of them.
    meeting = layers.module_resources("650dan")
    for name in ("k_650enter", "k_def_650kavar", "k_def_650vrook", "k_def_650zez"):
        original = layers.override(name, ResourceType.NCS) or meeting.get((name, ResourceType.NCS))
        if original is not None:
            (out / f"{name}.ncs").write_bytes(prepend_execute(original, "ap_masters"))
    (out / "globalcat.2da").write_bytes(merged_globalcat(layers, protocol))
    (out / "k2ap_build.txt").write_text(f"profile={profile}\ntable_hash={protocol.table_hash()}\n", encoding="utf-8")
    print(f"built {profile} into {out}: " + ", ".join(sorted(p.name for p in out.iterdir())))


if __name__ == "__main__":
    main()
